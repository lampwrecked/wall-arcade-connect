// The portraits of the wall (panels 501..550, "THE PFP CROWN"), copied into the build: the images live on the wall site's
// storage under addresses the public /positions data does not give, and are served without CORS, so a game cannot paint
// them into a WebGL texture at run time. This reads the addresses from the wall site's page, downloads each portrait into
// src/generated/portraits/<panel>.jpg (cropped square from the centre, 256 px: the wall draws them at about 160 px), and
// writes src/generated/portraits.ts (display only: never in a score).
// Usage: node --import tsx scripts/snapshot-portraits.ts
import { mkdir, readdir, rm, writeFile } from 'node:fs/promises';
import { createCanvas, loadImage } from '@napi-rs/canvas';

const SIZE = 256;

const SITE = 'https://onthewall.nfcsummit.com/';
const dir = new URL('../src/generated/portraits/', import.meta.url);
const html = await (await fetch(SITE)).text();
const found = new Map<number, string>();
for (const m of html.matchAll(/https:\/\/[a-z0-9.-]+\/positions\/(\d+)-[0-9a-f-]+\.(jpg|jpeg|png|webp)/gi)) {
  const panel = Number(m[1]);
  if (panel >= 501 && panel <= 550 && !found.has(panel)) found.set(panel, m[0]);
}
if (!found.size) throw new Error(`No portrait address found on ${SITE}: the page changed?`);

await mkdir(dir, { recursive: true });
for (const file of await readdir(dir)) await rm(new URL(file, dir));
const lines: string[] = [];
for (const [panel, url] of [...found].sort((a, b) => a[0] - b[0])) {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${url}: HTTP ${response.status}`);
  const image = await loadImage(Buffer.from(await response.arrayBuffer()));
  const side = Math.min(image.width, image.height), canvas = createCanvas(SIZE, SIZE);
  canvas.getContext('2d').drawImage(image, (image.width - side) / 2, (image.height - side) / 2, side, side, 0, 0, SIZE, SIZE);
  const bytes = await canvas.encode('jpeg', 86);
  await writeFile(new URL(`${panel}.jpg`, dir), bytes);
  lines.push(`import p${panel} from './portraits/${panel}.jpg';`);
  console.log(`${panel}: ${image.width}×${image.height} -> ${bytes.byteLength} B`);
}
const panels = [...found.keys()].sort((a, b) => a - b);
await writeFile(new URL('../src/generated/portraits.ts', import.meta.url),
  `// Generated by scripts/snapshot-portraits.ts on ${new Date().toISOString().slice(0, 10)} from ${SITE}: the wall's portraits by panel. Do not edit.\n`
  + `${lines.join('\n')}\n\nexport const PORTRAITS: Readonly<Record<number, string>> = { ${panels.map((p) => `${p}: p${p}`).join(', ')} };\n`);
console.log(`${panels.length} portraits: src/generated/portraits.ts`);
